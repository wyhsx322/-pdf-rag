# ── 便捷函数 ────────────────────────────────────────────────────────

def get_system_prompt(reasoning_mode: bool = False) -> str:
    """根据模式返回对应的系统提示词。

    Args:
        reasoning_mode: True 时返回多步推理提示词，False 时返回标准提示词。

    Returns:
        对应的系统提示词字符串。
    """
    return REASONING_SYSTEM_PROMPT if reasoning_mode else ACADEMIC_RAG_SYSTEM_PROMPT


def inject_few_shot_examples(user_prompt: str, max_examples: int = 2) -> str:
    """在用户提示词前注入 few-shot 示例。

    Args:
        user_prompt: 原始用户提示词。
        max_examples: 最多注入的示例数量。

    Returns:
        包含 few-shot 示例的完整提示词。
    """
    examples = FEW_SHOT_EXAMPLES[:max_examples]
    if not examples:
        return user_prompt

    parts = ["## 回答示例（请参考以下格式和风格）\n"]
    for i, ex in enumerate(examples, 1):
        parts.append(f"### 示例 {i}")
        parts.append(f"**问题**: {ex['question']}\n")
        parts.append(f"**回答**:\n{ex['answer']}\n")
    parts.append("---\n")
    parts.append(user_prompt)

    return "\n".join(parts)
